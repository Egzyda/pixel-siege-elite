// ============================================================
// スプライトの占有範囲（バウンディングボックス）キャッシュ
// 影の位置・HP バーの位置をスプライト実体に合わせるために使用する。
// ============================================================
const spriteBoxCache = new Map();

function getSpriteBox(sprite) {
    if(spriteBoxCache.has(sprite)) return spriteBoxCache.get(sprite);

    let minC = SPRITE_W, maxC = -1, minR = SPRITE_H, maxR = -1;
    for(let r = 0; r < sprite.length; r++) {
        for(let c = 0; c < sprite[r].length; c++) {
            if(sprite[r][c] > 0) {
                if(c < minC) minC = c;
                if(c > maxC) maxC = c;
                if(r < minR) minR = r;
                if(r > maxR) maxR = r;
            }
        }
    }
    if(maxC < 0) { minC = 0; maxC = SPRITE_W - 1; minR = 0; maxR = SPRITE_H - 1; }

    const box = {
        minC, maxC, minR, maxR,
        w: maxC - minC + 1,
        h: maxR - minR + 1,
        cx: (minC + maxC + 1) / 2 // 中心の列（ピクセル単位）
    };
    spriteBoxCache.set(sprite, box);
    return box;
}

// ============================================================
// スプライト描画（共通）
// x, y は「足元（スプライト下端）の中心」を表すアンカー位置。
// flipX を true にすると左右反転する（反転しても位置はズレない）。
// ============================================================
function drawSprite(ctx, sprite, pal, x, y, scale, opts) {
    const o = opts || {};
    const box = getSpriteBox(sprite);
    const white = o.flash === true;

    ctx.save();
    ctx.translate(x, y);
    if(o.flipX) ctx.scale(-1, 1);
    // 占有範囲の「下端」を y に、「中心」を x に合わせる
    ctx.translate(-box.cx * scale, -(box.maxR + 1) * scale);
    if(o.alpha !== undefined) ctx.globalAlpha = o.alpha;

    for(let r = box.minR; r <= box.maxR; r++) {
        const row = sprite[r];
        for(let c = box.minC; c <= box.maxC; c++) {
            const idx = row[c];
            if(idx > 0) {
                ctx.fillStyle = white ? '#ffffff' : (pal[idx] || '#ff00ff');
                ctx.fillRect(c * scale, r * scale, scale, scale);
            }
        }
    }
    ctx.restore();
}

// 足元の楕円シャドウ（スプライトの実寸に合わせる）
function drawShadow(ctx, sprite, x, y, scale, alpha) {
    const box = getSpriteBox(sprite);
    ctx.fillStyle = `rgba(0,0,0,${alpha === undefined ? 0.35 : alpha})`;
    ctx.beginPath();
    ctx.ellipse(x, y, (box.w * scale) / 2.2, (box.w * scale) / 6, 0, 0, Math.PI * 2);
    ctx.fill();
}
