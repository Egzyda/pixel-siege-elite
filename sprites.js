// #rrggbb 形式の色を [r,g,b] に変換する
function hexToRgb(hex) {
    const h = hex.replace('#', '');
    return [
        parseInt(h.substring(0, 2), 16),
        parseInt(h.substring(2, 4), 16),
        parseInt(h.substring(4, 6), 16)
    ];
}

// 2 色を amount(0〜1) の比率で混ぜる
function mixColor(hex, targetHex, amount) {
    if(!hex || hex[0] !== '#') return hex; // 透明色はそのまま
    const a = hexToRgb(hex), b = hexToRgb(targetHex);
    const c = a.map((v, i) => Math.round(v + (b[i] - v) * amount));
    return '#' + c.map(v => v.toString(16).padStart(2, '0')).join('');
}

// パレット全体を指定色に寄せた新しいパレットを作る
function tintPalette(pal, targetHex, amount) {
    return pal.map(c => mixColor(c, targetHex, amount));
}

